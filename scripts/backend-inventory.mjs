import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'

function findRepoRoot() {
  let current = process.cwd()
  for (;;) {
    if (existsSync(join(current, 'crates')) && existsSync(join(current, 'docs'))) {
      return current
    }
    const parent = dirname(current)
    if (parent === current) throw new Error('could not locate the repository root')
    current = parent
  }
}

export const ROOT = findRepoRoot()
const CRATES = join(ROOT, 'crates')
export const INVENTORY_PATH = join(ROOT, 'docs', 'backend-inventory.md')

const METHODS = ['get', 'post', 'put', 'patch', 'delete', 'head', 'options', 'any']

function walk(dir) {
  const out = []
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) {
      if (entry === 'tests' || entry === 'test') continue
      out.push(...walk(full))
    } else if (entry.endsWith('.rs')) {
      out.push(full)
    }
  }
  return out
}

function stripTestModules(source) {
  let out = source
  for (let from = 0; ; ) {
    const marker = out.indexOf('#[cfg(test)]', from)
    if (marker === -1) return out
    const braceStart = out.indexOf('{', marker)
    if (braceStart === -1) return out.slice(0, marker)
    let depth = 0
    let end = braceStart
    for (; end < out.length; end += 1) {
      if (out[end] === '{') depth += 1
      if (out[end] === '}') {
        depth -= 1
        if (depth === 0) break
      }
    }
    out = out.slice(0, marker) + out.slice(end + 1)
    from = marker
  }
}

function matchParen(source, openIndex) {
  let depth = 0
  let inString = false
  let escaped = false
  for (let i = openIndex; i < source.length; i += 1) {
    const ch = source[i]
    if (escaped) {
      escaped = false
      continue
    }
    if (ch === '\\') {
      escaped = true
      continue
    }
    if (ch === '"') {
      inString = !inString
      continue
    }
    if (inString) continue
    if (ch === '(') depth += 1
    if (ch === ')') {
      depth -= 1
      if (depth === 0) return i
    }
  }
  return -1
}

function extractRoutes(source) {
  const routes = []
  const needle = '.route('
  let from = 0
  for (;;) {
    const at = source.indexOf(needle, from)
    if (at === -1) return routes
    const open = at + needle.length - 1
    const close = matchParen(source, open)
    if (close === -1) return routes
    const span = source.slice(open, close + 1)
    const pathMatch = span.match(/"([^"]+)"/)
    if (pathMatch) {
      const methods = METHODS.filter((method) =>
        new RegExp(`(^|[^A-Za-z0-9_:])${method}\\s*\\(`).test(span),
      )
      for (const method of methods) {
        routes.push({ method: method.toUpperCase(), path: pathMatch[1] })
      }
    }
    from = close + 1
  }
}

const ALLOWLIST_PATTERN = /allowlist:\s*vec!\[([\s\S]*?)\]\s*,/g
const ALLOWLIST_ENTRY = /"([A-Z]+)\s+([^"]+)"/g

function extractAllowlist(source) {
  const entries = []
  for (const block of source.matchAll(ALLOWLIST_PATTERN)) {
    for (const entry of block[1].matchAll(ALLOWLIST_ENTRY)) {
      const method = entry[1]
      const path = entry[2].replace(/:([A-Za-z_][A-Za-z0-9_]*)/g, '{$1}')
      entries.push(`${method} ${path}`)
    }
  }
  return entries
}

export function collectRoutes() {
  const services = new Map()

  function serviceName(file) {
    return relative(ROOT, file).split('/')[1]
  }

  function ensure(service) {
    if (!services.has(service)) services.set(service, new Set())
    return services.get(service)
  }

  for (const file of walk(CRATES)) {
    const service = serviceName(file)
    const source = stripTestModules(readFileSync(file, 'utf8'))
    if (source.includes('create_router')) ensure(service)
    for (const route of extractRoutes(source)) {
      ensure(service).add(`${route.method} ${route.path}`)
    }
    for (const entry of extractAllowlist(source)) {
      ensure(service).add(entry)
    }
  }

  return services
}

export function renderInventory(services) {
  const total = [...services.values()].reduce((sum, set) => sum + set.size, 0)
  const empty = [...services.entries()]
    .filter(([, set]) => set.size === 0)
    .map(([name]) => name)

  const lines = [
  '# Backend Route Inventory',
  '',
  '| | |',
  '|---|---|',
  '| **Status** | Generated — do not edit by hand |',
  '| **Generated by** | `scripts/backend-inventory.mjs` |',
  `| **Date** | ${new Date().toISOString().slice(0, 10)} |`,
  `| **Routes found** | ${total} across ${services.size} crates |`,
  '',
  'Regenerate with `npm run inventory` from `frontend/`, or',
  '`node scripts/backend-inventory.mjs` from the repository root. CI fails if this',
  'file is stale, so adding a route without regenerating it breaks the build.',
  '',
  'A route appearing here means the endpoint is registered. It does not mean the',
  'handler is implemented: several handlers return hardcoded payloads. `405` and',
  '`415` responses prove a route exists, so never infer a missing route from a',
  'non-2xx status.',
  '',
]

if (empty.length > 0) {
  lines.push(
    '## Crates serving an empty router',
    '',
    'These build an HTTP router with no routes registered. The service starts and',
    'answers requests, but every path is a 404.',
    '',
    ...empty.map((name) => `- \`${name}\``),
    '',
  )
}

const sortedServices = [...services.keys()].sort()
for (const service of sortedServices) {
  lines.push(`## \`${service}\``, '')
  const entries = [...services.get(service)].sort()
  if (entries.length === 0) {
    lines.push('_No routes registered._', '')
    continue
  }
  lines.push('| Method | Path |', '|---|---|')
  for (const entry of entries) {
    const [method, ...rest] = entry.split(' ')
    lines.push(`| \`${method}\` | \`${rest.join(' ')}\` |`)
  }
  lines.push('')
}

return lines.join('\n')
}

if (process.argv[1]?.endsWith('backend-inventory.mjs')) {
  const services = collectRoutes()
  writeFileSync(INVENTORY_PATH, renderInventory(services))
  const total = [...services.values()].reduce((sum, set) => sum + set.size, 0)
  console.log(`backend-inventory: ok (${total} routes across ${services.size} crates)`)
}
